extension Copy {
    static func stars(_ count: Int) -> String {
        count == 1 ? "1 star" : "\(count) stars"
    }

    static func moreToGo(_ count: Int) -> String {
        "\(count) \(moreStars)"
    }

    static func waitingLine(for name: String) -> String {
        "\(name) \(waiting)"
    }

    static func reminder(kid: String, routine: String) -> String {
        "Time for \(kid)'s \(routine)."
    }

    static func progress(done: Int, total: Int) -> String {
        "\(done) \(ofWord) \(total) \(finishedWord)"
    }

    static func bonus(_ count: Int) -> String {
        "\(bonusPrefix) \(stars(count))."
    }

    static func stageName(_ mark: Int) -> String {
        "Stage \(mark)"
    }

    static func streak(_ count: Int) -> String {
        count == 0 ? noStreak : "\(count) \(dayStreak)"
    }

    static func goodMorning(_ name: String) -> String { "Good morning, \(name)." }
    static func goodAfternoon(_ name: String) -> String { "Hi, \(name)." }
    static func goodEvening(_ name: String) -> String { "Good evening, \(name)." }
    static func finishedDays(_ done: Int, _ total: Int) -> String { "\(done) of \(total) days finished." }
}
